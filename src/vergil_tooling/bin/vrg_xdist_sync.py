"""``vrg-xdist-sync`` — add ``pytest-xdist`` to every Python repo's dev deps.

A shape-aware entry to the generic fleet-sweep driver
(:mod:`vergil_tooling.lib.fleet_sweep`, epic vergil-project/.github#333, Task 9).
It builds the xdist :class:`~vergil_tooling.lib.fleet_sweep.SweepSpec` and drives
:func:`~vergil_tooling.lib.fleet_sweep.run_sweep` with
:func:`~vergil_tooling.lib.xdist_applicator.add_xdist` — one PR per repo whose dev
dependencies actually need ``pytest-xdist``.

Per the "no silent failures" policy, a repo whose dev-dependency shape the
applicator cannot classify is **not** silently skipped: it is flagged
``needs_followup``, reported in a prominent post-sweep summary, and a follow-up
issue is filed against it so the gap is tracked rather than lost.

Each repo in ``--repos`` is a path to a local clone. ``--dry-run`` reports the
intended action per repo without touching any git or GitHub state (no worktree,
no issue, no commit, no PR, and no follow-up issues).

This tool never submits or merges a PR — it stops at ``report-ready``, exactly
like any other agent-run task. **Running the sweep across the fleet is a
human-run rollout**, and should follow the shared TEST command adopting
``-n auto --dist worksteal`` (Task 6) — until then a repo carrying
``pytest-xdist`` gains no parallelism.
"""

from __future__ import annotations

import argparse
import re
import subprocess  # noqa: S404 - fixed vrg-* argv, never shell
import sys

from vergil_tooling.lib.fleet_sweep import RepoResult, SweepSpec, run_sweep
from vergil_tooling.lib.xdist_applicator import add_xdist

_TITLE = "chore(test): add pytest-xdist to dev dependencies for parallel test runs"
_BODY = (
    "Add `pytest-xdist` to this repository's development dependencies so the "
    "shared `vrg-validate` TEST command can run the suite in parallel "
    "(`-n auto --dist worksteal`). Generated by the fleet-sweep driver "
    "(epic vergil-project/.github#333, Task 9)."
)

_FOLLOWUP_TITLE = "chore(test): add pytest-xdist manually (unclassifiable dev-dependency shape)"
_FOLLOWUP_BODY = (
    "The `vrg-xdist-sync` fleet sweep (epic vergil-project/.github#333, Task 9) "
    "could not classify this repository's development-dependency shape, so it "
    "made **no** edit rather than guess. Add `pytest-xdist` to the dev "
    "dependencies by hand so the suite can run in parallel under the shared "
    "TEST command. Filed automatically because the sweep reports loudly instead "
    'of silently skipping (repo "no silent failures" policy).'
)

_ISSUE_URL_RE = re.compile(r"/issues/(\d+)")

_DRY_RUN_FOLLOWUP_ACTION = "dry-run: would file a follow-up issue"


def _parse_args(argv: list[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="vrg-xdist-sync",
        description=(
            "Add pytest-xdist to each Python repo's dev dependencies, opening "
            "one PR per repo that needs it. Repos whose dev-dependency shape "
            "cannot be classified are reported loudly and get a follow-up "
            "issue. Never submits or merges — stops at report-ready."
        ),
    )
    parser.add_argument(
        "--repos",
        nargs="+",
        required=True,
        metavar="PATH",
        help="Local clone path(s) of the repositories to sweep.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Report the intended action per repo without touching git/GitHub state.",
    )
    return parser.parse_args(argv)


def _file_followup(repo: str) -> str:
    """File a follow-up issue against *repo* for a manual pytest-xdist add.

    Returns a human-readable outcome line. A ``vrg-issue-create`` failure is
    caught and surfaced in that line rather than aborting the summary — the
    unclassified repo is already reported loudly regardless.
    """
    result = subprocess.run(  # noqa: S603 - fixed vrg-issue-create argv, no shell
        [  # noqa: S607
            "vrg-issue-create",
            "--epic",
            "adhoc",
            "--title",
            _FOLLOWUP_TITLE,
            "--body",
            _FOLLOWUP_BODY,
        ],
        cwd=repo,
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        detail = (result.stderr or result.stdout).strip()
        return f"FAILED to file follow-up issue: {detail}"
    match = _ISSUE_URL_RE.search(result.stdout)
    return f"filed follow-up issue #{match.group(1)}" if match else "filed follow-up issue"


def _report_followups(followups: list[RepoResult], *, dry_run: bool) -> None:
    """Print a prominent summary of every ``needs_followup`` repo, filing issues.

    In ``dry_run`` mode no issue is filed (no GitHub state is touched); the
    summary states what a live run would do instead.
    """
    print("\n" + "=" * 72)
    print(
        f"NEEDS FOLLOW-UP: {len(followups)} repo(s) could not be classified "
        "— pytest-xdist NOT added"
    )
    print("=" * 72)
    for result in followups:
        action = _DRY_RUN_FOLLOWUP_ACTION if dry_run else _file_followup(result.repo)
        print(f"  {result.repo}: {result.detail}\n    -> {action}")


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv)
    spec = SweepSpec(
        repos=list(args.repos),
        branch_slug="add-pytest-xdist",
        title=_TITLE,
        body=_BODY,
        commit_type="chore",
        commit_scope="test",
        epic=None,
    )
    results = run_sweep(spec, add_xdist, dry_run=args.dry_run)
    for result in results:
        print(f"{result.status:8} {result.repo}  {result.detail}")

    followups = [r for r in results if r.needs_followup]
    if followups:
        _report_followups(followups, dry_run=args.dry_run)

    return 1 if any(r.status == "error" for r in results) else 0


if __name__ == "__main__":
    sys.exit(main())
