"""``vrg-ci-sync`` — fleet sweep that strips the hardcoded matrix from ``ci.yml``.

A :mod:`~vergil_tooling.lib.fleet_sweep` consumer (mirroring
:mod:`~vergil_tooling.bin.vrg_fleet_sync`) that propagates one bespoke change
across a fleet: it removes the retired ``versions:`` / ``container-tag:`` inputs
from every reusable-workflow call in each repo's ``.github/workflows/ci.yml``,
converging the file onto the thin-caller shape. The reusable workflows now
resolve the version matrix and container tag from ``vergil.toml`` themselves
(epic vergil-project/.github#338).

The bespoke change is
:func:`~vergil_tooling.lib.ci_yml_applicator.strip_matrix_inputs`; the generic
work-chain (probe worktree, tracking issue, branch, commit, ``report-ready``) is
owned by :func:`~vergil_tooling.lib.fleet_sweep.run_sweep`. One PR per repo whose
``ci.yml`` actually drifts; a repo already thin is skipped with no issue or PR.

This tool **never** submits or merges a PR — it stops at ``report-ready``, exactly
like any other agent-run task. The human runs the sweep and, later, ``vrg-submit-pr``.

Each ``--repos`` entry is a path to a local clone, absolute or relative (the
driver resolves it, #2979). ``--dry-run`` runs the applicator in check-only mode
in a disposable probe worktree and reports the verdict a live run would reach per
repo, without opening an issue, branch, commit, or PR (#3549). A repo whose ``ci.yml`` shape cannot
be understood is left unchanged and listed **prominently** in a follow-up
report — never silently skipped (this repo's "no silent failures" policy).

Each repo's tracking issue links under that repo's **own** org ad-hoc epic
(``epic=None``), like ``vrg-fleet-sync`` and ``vrg-xdist-sync``: the fleet spans
several orgs and ``vrg-issue-create`` refuses a cross-org epic link (#3015).
"""

from __future__ import annotations

import argparse
import sys

from vergil_tooling.lib.ci_yml_applicator import strip_matrix_inputs
from vergil_tooling.lib.cli import cli_main
from vergil_tooling.lib.fleet_sweep import SweepSpec, run_sweep

_TITLE = "refactor(ci): drop the hardcoded matrix inputs from ci.yml"
_BODY = (
    "Remove the `versions:` and `container-tag:` inputs from every "
    "reusable-workflow call in `.github/workflows/ci.yml`, converging the file "
    "onto the thin-caller shape. The reusable workflows now resolve the version "
    "matrix and container tag from `vergil.toml` themselves "
    "(epic vergil-project/.github#338). Generated by the fleet-sweep driver."
)


@cli_main
def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv)
    spec = SweepSpec(
        repos=args.repos,
        branch_slug="ci-sync",
        title=_TITLE,
        body=_BODY,
        commit_type="refactor",
        commit_scope="ci",
        # No fixed epic: each repo's task links under its OWN org's ad-hoc
        # epic. A hardcoded vergil-project epic made vrg-issue-create refuse
        # every repo in another org as a cross-org link (#3015).
        epic=None,
    )
    results = run_sweep(spec, strip_matrix_inputs, dry_run=args.dry_run)
    for result in results:
        print(f"{result.status:8} {result.repo}  {result.detail}")

    # Surface every repo the applicator recognized but could not safely edit,
    # loudly and in full — no silent truncation (this repo's no-silent-failures
    # policy). These need a human to reconcile the repo's ci.yml shape by hand.
    followups = [r for r in results if r.needs_followup]
    if followups:
        print(f"\nNEEDS FOLLOW-UP — {len(followups)} repo(s) left unchanged (unrecognized ci.yml):")
        for result in followups:
            print(f"  {result.repo}  {result.detail}")

    return 1 if any(r.status == "error" for r in results) else 0


def _parse_args(argv: list[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="vrg-ci-sync",
        description=(
            "Strip the hardcoded versions:/container-tag: matrix inputs from each "
            "repo's ci.yml across a fleet, opening one PR per repo whose ci.yml "
            "drifts. Never submits or merges — stops at report-ready."
        ),
    )
    parser.add_argument(
        "--repos",
        nargs="+",
        required=True,
        metavar="PATH",
        help="Local clone path(s) of the repositories to sweep.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help=(
            "Preview the verdict a live run would reach per repo (check-only, in a "
            "disposable probe worktree) without opening an issue, branch, commit, or PR."
        ),
    )
    return parser.parse_args(argv)


if __name__ == "__main__":
    sys.exit(main())
