"""``vrg-fleet-sync`` — propagate a vergil-managed file across a fleet.

The configured entry to the generic fleet-sweep driver
(:mod:`vergil_tooling.lib.fleet_sweep`, epic vergil-project/.github#325, Task 7).
Each ``--target`` names a managed file with its own
:class:`~vergil_tooling.lib.fleet_sweep.SweepSpec` fields and a single-repo
applicator CLI that the sweep shells out to once per repo worktree:

* ``gitignore`` (default) — ``vrg-gitignore-sync --write --repo <worktree>``,
  the managed ``.gitignore`` block (epic #325).
* ``dependabot`` — ``vrg-dependabot-sync --write --repo <worktree>``, the
  canonical report-only ``.github/dependabot.yml`` (epic .github#420). A repo
  outside the ``vergil-project`` org is filed under its own ad-hoc epic
  instead, since a cross-org epic link is refused (#3447).

The sweep opens one PR per repo whose file actually drifts. The target table is
hard-coded; a config-driven or general change-script CLI is follow-on #328.
This tool never submits or merges a PR — it stops at ``report-ready``, exactly
like any other agent-run task.

Each repo in ``--repos`` is a path to a local clone (the worktree is created
inside it). ``--dry-run`` reports the intended action per repo without touching
any git or GitHub state.
"""

from __future__ import annotations

import argparse
import subprocess  # noqa: S404 - fixed applicator argv, never shell
import sys
from dataclasses import dataclass
from typing import TYPE_CHECKING

from vergil_tooling.lib.cli import cli_main
from vergil_tooling.lib.fleet_sweep import AppResult, SweepSpec, run_sweep

if TYPE_CHECKING:
    from pathlib import Path


@dataclass(frozen=True)
class _Target:
    """One sweepable managed file: its PR/commit shape and applicator CLI."""

    applicator_cli: str
    branch_slug: str
    title: str
    body: str
    commit_scope: str
    epic: str | None


_TARGETS: dict[str, _Target] = {
    "gitignore": _Target(
        applicator_cli="vrg-gitignore-sync",
        branch_slug="gitignore-sync",
        title="chore(gitignore): sync the vergil-managed .gitignore block",
        body=(
            "Propagate the composed vergil-managed `.gitignore` block "
            "(base + primary-language fragment) into this repository, dropping any "
            "stale other-language lines. Generated by the fleet-sweep driver "
            "(epic vergil-project/.github#325)."
        ),
        commit_scope="gitignore",
        epic=None,
    ),
    "dependabot": _Target(
        applicator_cli="vrg-dependabot-sync",
        branch_slug="dependabot-config",
        title="chore(dependabot): add the report-only dependabot.yml",
        body=(
            "Write the canonical report-only `.github/dependabot.yml`: Dependabot "
            "alerts stay on, but every `updates` entry carries "
            "`open-pull-requests-limit: 0`, so Dependabot never opens a PR. "
            "Generated by the fleet-sweep driver (epic vergil-project/.github#420)."
        ),
        commit_scope="dependabot",
        epic="vergil-project/.github#420",
    ),
}

_DEFAULT_TARGET = "gitignore"


@cli_main
def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv)
    target = _TARGETS[args.target]
    spec = SweepSpec(
        repos=list(args.repos),
        branch_slug=target.branch_slug,
        title=target.title,
        body=target.body,
        commit_type="chore",
        commit_scope=target.commit_scope,
        epic=target.epic,
    )

    def applicator(worktree: Path) -> AppResult:
        return _run_sync_applicator([target.applicator_cli, "--write", "--repo"], worktree)

    results = run_sweep(spec, applicator, dry_run=args.dry_run)
    for result in results:
        print(f"{result.status:8} {result.repo}  {result.detail}")
    return 1 if any(r.status == "error" for r in results) else 0


def _parse_args(argv: list[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="vrg-fleet-sync",
        description=(
            "Propagate a vergil-managed file (--target: the .gitignore managed "
            "block, or the report-only .github/dependabot.yml) across a fleet of "
            "repositories, opening one PR per repo whose file drifts. "
            "Never submits or merges — stops at report-ready."
        ),
    )
    parser.add_argument(
        "--repos",
        nargs="+",
        required=True,
        metavar="PATH",
        help="Local clone path(s) of the repositories to sweep.",
    )
    parser.add_argument(
        "--target",
        choices=sorted(_TARGETS),
        default=_DEFAULT_TARGET,
        help=f"The managed file to sweep (default: {_DEFAULT_TARGET}).",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Report the intended action per repo without touching git/GitHub state.",
    )
    return parser.parse_args(argv)


def _run_sync_applicator(argv: list[str], worktree: Path) -> AppResult:
    """Run one single-repo applicator CLI (``argv`` + ``<worktree>``).

    Each applicator's ``--write`` prints ``already in sync`` when the file is
    already current (no change) and a summary line when it rewrote the file;
    that distinction is mapped to :attr:`AppResult.changed`. A non-zero exit
    raises so the driver records the repo as an error.
    """
    result = subprocess.run(  # noqa: S603 - fixed argv, no shell, no interpolation
        [*argv, str(worktree)],
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        detail = (result.stderr or result.stdout).strip()
        raise RuntimeError(f"{argv[0]} failed (exit {result.returncode}): {detail}")
    output = result.stdout.strip()
    changed = "already in sync" not in output
    return AppResult(changed=changed, summary=output)


if __name__ == "__main__":
    sys.exit(main())
