"""``vrg-fleet-sync`` — propagate the managed ``.gitignore`` block across a fleet.

The gitignore-configured entry to the generic fleet-sweep driver
(:mod:`vergil_tooling.lib.fleet_sweep`, epic vergil-project/.github#325, Task 7).
It builds the gitignore :class:`~vergil_tooling.lib.fleet_sweep.SweepSpec` and an
applicator that shells out to ``vrg-gitignore-sync --write --repo <worktree>``
for one repo, then drives :func:`~vergil_tooling.lib.fleet_sweep.run_sweep` over
the given repos — one PR per repo whose ``.gitignore`` actually drifts.

gitignore is the **sole** consumer of the seam in this epic; a config-driven or
general change-script CLI is follow-on #328. This tool never submits or merges
a PR — it stops at ``report-ready``, exactly like any other agent-run task.

Each repo in ``--repos`` is a path to a local clone (the worktree is created
inside it). ``--dry-run`` reports the intended action per repo without touching
any git or GitHub state.
"""

from __future__ import annotations

import argparse
import subprocess  # noqa: S404 - fixed vrg-gitignore-sync argv, never shell
import sys
from typing import TYPE_CHECKING

from vergil_tooling.lib.fleet_sweep import AppResult, SweepSpec, run_sweep

if TYPE_CHECKING:
    from pathlib import Path

_TITLE = "chore(gitignore): sync the vergil-managed .gitignore block"
_BODY = (
    "Propagate the composed vergil-managed `.gitignore` block "
    "(base + primary-language fragment) into this repository, dropping any "
    "stale other-language lines. Generated by the fleet-sweep driver "
    "(epic vergil-project/.github#325)."
)


def _gitignore_applicator(worktree: Path) -> AppResult:
    """Sync one worktree's ``.gitignore`` via the single-repo applicator CLI.

    ``vrg-gitignore-sync --write`` prints ``already in sync`` when the block is
    already current (no change) and a ``synced managed block …`` line when it
    rewrote the file; that distinction is mapped to :attr:`AppResult.changed`.
    A non-zero exit raises so the driver records the repo as an error.
    """
    result = subprocess.run(  # noqa: S603 - fixed argv, no shell, no interpolation
        ["vrg-gitignore-sync", "--write", "--repo", str(worktree)],  # noqa: S607
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        detail = (result.stderr or result.stdout).strip()
        raise RuntimeError(f"vrg-gitignore-sync failed (exit {result.returncode}): {detail}")
    output = result.stdout.strip()
    changed = "already in sync" not in output
    return AppResult(changed=changed, summary=output)


def _parse_args(argv: list[str] | None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        prog="vrg-fleet-sync",
        description=(
            "Propagate the vergil-managed .gitignore block across a fleet of "
            "repositories, opening one PR per repo whose .gitignore drifts. "
            "Never submits or merges — stops at report-ready."
        ),
    )
    parser.add_argument(
        "--repos",
        nargs="+",
        required=True,
        metavar="PATH",
        help="Local clone path(s) of the repositories to sweep.",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Report the intended action per repo without touching git/GitHub state.",
    )
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = _parse_args(argv)
    spec = SweepSpec(
        repos=list(args.repos),
        branch_slug="gitignore-sync",
        title=_TITLE,
        body=_BODY,
        commit_type="chore",
        commit_scope="gitignore",
        epic=None,
    )
    results = run_sweep(spec, _gitignore_applicator, dry_run=args.dry_run)
    for result in results:
        print(f"{result.status:8} {result.repo}  {result.detail}")
    return 1 if any(r.status == "error" for r in results) else 0


if __name__ == "__main__":
    sys.exit(main())
